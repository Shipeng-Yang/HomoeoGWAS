def _load_contexts(root: Path, scenarios: Sequence[Scenario]) -> dict[str, OmniBBenchmarkContext]:
    lock = _strict_json(root / "design_lock.json")
    input_records = lock["input_records"]
    manifest = {
        str((root / path).resolve()) if path.startswith("inputs/") else path: row["sha256"]
        for path, row in input_records.items()
    }
    manifest.update({str((root / path).resolve()): digest for path, digest in lock["config_hashes"].items()})
    needed = set()
    for scenario in scenarios:
        if scenario.track != "omnib":
            continue
        backbone = str(scenario.parameters["backbone"])
        needed.add(
            f"{backbone}:g{scenario.parameters['family_size']}"
            if scenario.parameters.get("experiment") == "family_size" else backbone
        )
    contexts = {}
    for key in sorted(needed):
        record = lock["benchmark_contexts"][key]
        matching = next(
            scenario for scenario in scenarios
            if scenario.track == "omnib" and (
                (f"{scenario.parameters['backbone']}:g{scenario.parameters['family_size']}"
                 if scenario.parameters.get("experiment") == "family_size"
                 else str(scenario.parameters["backbone"])) == key
            )
        )
        config = root / lock["scenario_config_bindings"][matching.scenario_id]
        contexts[key] = load_omnib_benchmark_context(
            config, context_artifact_path=root / record["artifact_path"],
            input_manifest=manifest,
        )
    return contexts


def _fit_panel_context(root: Path, panel: str) -> dict[str, Any]:
    from homoeogwas.cli import build_kernels, join_samples
    from homoeogwas.io import load_bed_hardcall

    lock = _strict_json(root / "design_lock.json")
    spec = _strict_input_spec(Path(str(lock["operator_input_spec"])))
    entry = spec["fit"][panel]
    generic_path = root / lock["scenario_config_bindings"][
        f"A.recovery.{panel}.balanced"
    ]
    config = yaml.safe_load(generic_path.read_text(encoding="utf-8"))
    samples, anchor_y, covariates = join_samples(config)
    kernels, _info = build_kernels(config, samples)
    sample_ids = [str(value) for value in samples]
    standardized: dict[str, np.ndarray] = {}
    variant_ids: dict[str, list[str]] = {}
    positions: dict[str, list[int]] = {}
    for label in entry["subgenomes"]:
        prefix = Path(str(entry["bed_prefix_template"]).format(subgenome=label))
        chunk = load_bed_hardcall(prefix)
        by_sample = {str(value): index for index, value in enumerate(chunk.samples)}
        indices = np.asarray([by_sample[value] for value in sample_ids], dtype=int)
        dosage = np.asarray(chunk.dosage[indices, :], dtype=float)
        for column in range(dosage.shape[1]):
            values = dosage[:, column]
            if np.any(~np.isfinite(values)):
                finite = values[np.isfinite(values)]
                if finite.size == 0:
                    values = np.zeros_like(values)
                else:
                    values = np.where(np.isfinite(values), values, finite.mean())
            scale = np.std(values, ddof=1)
            dosage[:, column] = (
                (values - values.mean()) / scale if scale > 0 else 0.0
            )
        standardized[str(label)] = dosage
        variant_ids[str(label)] = [str(value) for value in chunk.variant_ids]
        positions[str(label)] = [int(value) for value in chunk.pos]
    fixed = np.asarray(covariates, dtype=float)
    if fixed.ndim != 2 or fixed.shape[1] < 1:
        fixed = np.ones((len(sample_ids), 1), dtype=float)
    return {
        "entry": entry, "samples": sample_ids, "anchor_y": np.asarray(anchor_y),
        "covariates": fixed, "kernels": kernels, "standardized": standardized,
        "variant_ids": variant_ids, "positions": positions,
    }


def _scan_comparators_for_scenario(
    scenario: Scenario, context: Mapping[str, Any], design_hash: str, replicate: int,
) -> Mapping[str, Any]:
    seed = derive_seed(design_hash, "fit", scenario.scenario_id, replicate, scenario.stage)
    rng = np.random.default_rng(seed)
    residual = rng.normal(size=len(context["samples"]))
    pve = float(scenario.parameters["scan_pve"])
    placement = str(scenario.parameters["placement"])
    selected_labels = list(context["kernels"])[
        : (1 if placement == "one_subgenome" else 2)
    ]
    causal = []
    signal = np.zeros(len(context["samples"]), dtype=float)
    if pve > 0:
        for label in selected_labels:
            block = np.asarray(context["standardized"][label])
            informative = next(
                (index for index in range(block.shape[1]) if np.std(block[:, index], ddof=1) > 0),
                None,
            )
            if informative is None:
                raise CLIError(f"scan panel has no informative variant in {label}")
            signal += block[:, informative]
            causal.append({
                "variant_id": context["variant_ids"][label][informative],
                "subgenome": label,
            })
        phenotype, metadata = compose_exact_pve(signal, residual, pve)
        realized = float(metadata["realized_pve"])
    else:
        phenotype = standardize(residual)
        realized = 0.0
    return build_scan_comparators(
        context["kernels"], sample_ids=context["samples"],
        variant_ids=context["variant_ids"],
        variant_positions_bp=context["positions"],
        standardized_variants=context["standardized"], phenotype=phenotype,
        covariates=context["covariates"],
        truth_metadata={
            "placement": placement, "scan_pve": pve,
            "realized_signal_pve": realized, "causal_variants": causal,
        },
    )


def _run_fit_scenario(
    root: Path, scenario: Scenario, *, design_hash: str,
    panel_contexts: dict[str, dict[str, Any]],
) -> None:
    panel = str(scenario.parameters["panel"])
    if panel not in panel_contexts:
        panel_contexts[panel] = _fit_panel_context(root, panel)
    context = panel_contexts[panel]
    lock = _strict_json(root / "design_lock.json")
    for replicate in range(scenario.replicates):
        shard = root / "pilot" / "fit" / scenario.scenario_id / f"replicate-{replicate:06d}.json"
        if shard.is_file():
            continue
        replicate_root = (
            root / "work" / "fit" / scenario.stage / scenario.scenario_id
            / f"replicate-{replicate:06d}"
        )

        def execute(
            replicate: int = replicate,
            replicate_root: Path = replicate_root,
        ) -> dict[str, Any]:
            experiment = str(scenario.parameters["experiment"])
            kwargs: dict[str, Any] = {}
            if experiment == "scan":
                kwargs["scan_comparators"] = _scan_comparators_for_scenario(
                    scenario, context, design_hash, replicate,
                )
                preflight = lock["comparator_preflights"][panel]
                kwargs["comparator_preflight_path"] = root / preflight["path"]
                kwargs["comparator_preflight_hash"] = preflight["sha256"]
            elif experiment == "coverage":
                seed = derive_seed(
                    design_hash, "fit", scenario.scenario_id, replicate,
                    scenario.stage,
                )
                from .track_fit import simulate_fit_truth

                phenotype, _truth = simulate_fit_truth(
                    context["kernels"], str(scenario.parameters["allocation"]),
                    seed=seed, total_pve=scenario.parameters.get("total_pve"),
                )
                phenotype_path = replicate_root / "phenotype.tsv"
                phenotype_path.parent.mkdir(parents=True, exist_ok=True)
                entry = context["entry"]
                phenotype_path.write_text(
                    f"{entry['sample_col']}\t{entry['trait']}\n" + "".join(
                        f"{sample}\t{float(value):.17g}\n"
                        for sample, value in zip(
                            context["samples"], phenotype, strict=True,
                        )
                    ), encoding="utf-8",
                )
                fixture = {
                    "panel": panel, "subgenomes": list(entry["subgenomes"]),
                    "phenotype": str(phenotype_path),
                    "sample_col": entry["sample_col"], "trait": entry["trait"],
                    "bed_prefixes": {
                        label: str(entry["bed_prefix_template"]).format(
                            subgenome=label
                        )
                        for label in entry["subgenomes"]
                    },
                }
                config_path = replicate_root / "configs" / "fit.generated.yaml"
                summary_path = (
                    replicate_root / "results" / f"summary_{entry['trait']}.json"
                )
                if not summary_path.is_file():
                    results = replicate_root / "results"
                    if results.exists() and any(results.iterdir()):
                        raise CLIError(
                            "partial coverage output requires repair: "
                            f"{scenario.scenario_id}/{replicate}"
                        )
                    build_fit_config(
                        fixture, replicate_root, coverage=True,
                        bootstrap_B=scenario.bootstrap_B, bootstrap_jobs=1,
                    )
                    if run_command(
                        ("homoeogwas", "fit", "-c", str(config_path))
                    ) != 0:
                        raise CLIError(
                            "released coverage fit failed: "
                            f"{scenario.scenario_id}/{replicate}"
                        )
                kwargs["fit_output_dir"] = replicate_root
                kwargs["trait"] = str(entry["trait"])
            elif experiment == "loco":
                record = lock["loco_truth_artifacts"][scenario.stage][
                    scenario.scenario_id
                ][str(replicate)]
                source_relative = (
                    f"configs/fit/{scenario.stage}/loco/{scenario.scenario_id}/"
                    f"replicate-{replicate:06d}.generated.yaml"
                )
                config_path = replicate_root / "configs" / "fit.generated.yaml"
                summary_path = (
                    replicate_root / "results"
                    / f"summary_{context['entry']['trait']}.json"
                )
                if not summary_path.is_file():
                    results = replicate_root / "results"
                    if results.exists() and any(results.iterdir()):
                        raise CLIError(
                            "partial LOCO output requires repair: "
                            f"{scenario.scenario_id}/{replicate}"
                        )
                    config_path.parent.mkdir(parents=True, exist_ok=True)
                    config_path.write_bytes((root / source_relative).read_bytes())
                    if _sha256(config_path) != record["generated_config_sha256"]:
                        raise CLIError("LOCO final config differs from presealed design")
                    if run_command(
                        ("homoeogwas", "fit", "-c", str(config_path))
                    ) != 0:
                        raise CLIError(
                            f"released LOCO fit failed: {scenario.scenario_id}/{replicate}"
                        )
                elif _sha256(config_path) != record["generated_config_sha256"]:
                    raise CLIError("completed LOCO config differs from presealed design")
                kwargs.update({
                    "fit_output_dir": replicate_root,
                    "trait": str(context["entry"]["trait"]),
                    "loco_design_root": root,
                })
            return run_fit_replicate(
                scenario, context["kernels"], replicate=replicate,
                design_hash=design_hash, sample_ids=context["samples"],
                **kwargs,
            )

        payload, measurement = _measure_operation(execute)
        measured = _attach_measurement(root, replicate_root, payload, measurement)
        write_shard_exclusive(shard, measured)


def _run_scaling_scenario(root: Path, scenario: Scenario, design_hash: str) -> None:
    from .contracts import ScalingAnchor

    value = scenario.parameters["anchor"]
    if isinstance(value, ScalingAnchor):
        value = value.to_dict()
    if not isinstance(value, Mapping):
        raise CLIError(f"invalid scaling anchor: {scenario.scenario_id}")
    anchor = ScalingAnchor(
        str(value["anchor_id"]), int(value["n"]), int(value["groups"]),
        int(value["copies"]), int(value["edges"]), int(value["bootstrap_B"]),
        tuple(int(item) for item in value["jobs"]), int(value["repeats"]),
    )
    shard = root / "pilot" / "scaling" / scenario.scenario_id / "replicate-000000.json"
    if shard.is_file():
        return
    measured, measurement = _measure_operation(lambda: run_anchor(anchor))
    payload = {
        "track": "scaling", "scenario_id": scenario.scenario_id, "replicate": 0,
        "design_hash": design_hash, "stage": "pilot", "formal": False,
        "qa_only": True, "inference_status": "noninferential_do_not_threshold",
        "experiment": scenario.parameters.get("experiment"),
        "request_hash": sha256_payload({"scenario": scenario.to_dict()}),
        "context_fingerprint": sha256_payload(value),
        "summary": summarize_anchor(anchor, measured),
        "failure": {"failed": False, "error_type": None, "message": None},
    }
    output_root = root / "work" / "scaling" / scenario.scenario_id / "replicate-000000"
    write_shard_exclusive(
        shard,
        _attach_measurement(root, output_root, payload, measurement),
    )


def _run_application_scenario(root: Path, scenario: Scenario, design_hash: str) -> None:
    shard = root / "pilot" / "application" / scenario.scenario_id / "replicate-000000.json"
    if shard.is_file():
        return
    lock = _strict_json(root / "design_lock.json")
    species = str(scenario.parameters["species"]).lower()
    aliases = _APPLICATION_SPECIES.get(species)
    if aliases is None:
        raise CLIError(f"application scenario has unsupported species {species!r}")
    rows, measurement = _measure_operation(lambda: [
        row for row in export_application_rows(lock["application_registry"])
        if str(row.get("species", "")).strip().lower() in aliases
    ])
    if not rows:
        raise CLIError(f"application registry has no frozen {species} row")
    payload = {
        "track": "application", "scenario_id": scenario.scenario_id, "replicate": 0,
        "design_hash": design_hash, "stage": "pilot", "formal": False,
        "qa_only": True, "inference_status": "noninferential_do_not_threshold",
        "experiment": scenario.parameters.get("experiment"),
        "request_hash": sha256_payload({"scenario": scenario.to_dict()}),
        "context_fingerprint": sha256_payload({"species": species}),
        "rows": rows,
        "failure": {"failed": False, "error_type": None, "message": None},
    }
    output_root = root / "work" / "application" / scenario.scenario_id / "replicate-000000"
    write_shard_exclusive(
        shard,
        _attach_measurement(root, output_root, payload, measurement),
    )


def _dispatch_pilot(root: Path, scenarios: Sequence[Scenario], *, n_jobs: int) -> None:
    if n_jobs < 1:
        raise CLIError("--n-jobs must be positive")
    contexts = _load_contexts(root, scenarios)
    lock = _strict_json(root / "design_lock.json")
    design_hash = str(lock["design_hash"])
    calibration: dict[str, ConditionalBank] = {}
    panel_contexts: dict[str, dict[str, Any]] = {}
    for scenario in scenarios:
        if scenario.track == "fit":
            _run_fit_scenario(
                root, scenario, design_hash=design_hash,
                panel_contexts=panel_contexts,
            )
            continue
        if scenario.track == "scaling":
            _run_scaling_scenario(root, scenario, design_hash)
            continue
        if scenario.track == "application":
            _run_application_scenario(root, scenario, design_hash)
            continue
        backbone = str(scenario.parameters["backbone"])
        key = (
            f"{backbone}:g{scenario.parameters['family_size']}"
            if scenario.parameters.get("experiment") == "family_size" else backbone
        )
        replicates = (
            range(1) if scenario.parameters.get("experiment") in {
                "conditional", "global_vc", "family_size",
            } else range(scenario.replicates)
        )
        for replicate in replicates:
            path = root / "pilot" / "omnib" / scenario.scenario_id / f"replicate-{replicate:06d}.json"
            bank = None
            if scenario.parameters.get("experiment") == "power":
                bank = calibration.get(backbone)
                if bank is None:
                    calibration_path = root / "pilot" / "omnib" / str(
                        scenario.parameters["calibration_scenario_id"]
                    ) / "replicate-000000.json"
                    if not calibration_path.is_file():
                        raise CLIError(
                            f"power requires its frozen calibration shard first: {calibration_path}"
                        )
                    bank = ConditionalBank.from_shard(calibration_path)
                    calibration[backbone] = bank
            if path.is_file():
                result = run_omnib_replicate(
                    scenario, contexts[key], replicate=replicate,
                    design_hash=design_hash, n_jobs=n_jobs, shard_path=path,
                    power_calibration_bank=bank,
                )
            else:
                context = contexts[key]
                result, measurement = _measure_operation(
                    lambda scenario=scenario, context=context,
                    replicate=replicate, bank=bank: run_omnib_replicate(
                        scenario, context, replicate=replicate,
                        design_hash=design_hash, n_jobs=n_jobs,
                        power_calibration_bank=bank,
                    )
                )
                output_root = (
                    root / "work" / "omnib" / scenario.scenario_id
                    / f"replicate-{replicate:06d}"
                )
                result = _attach_measurement(
                    root, output_root, result, measurement,
                )
                write_shard_exclusive(path, result)
            if (
                scenario.parameters.get("experiment") == "conditional"
                and scenario.parameters.get("bank") == "calibration"
                and scenario.parameters.get("null_model") == "gaussian"
            ):
                calibration[backbone] = ConditionalBank.from_payload(result["bank"])


