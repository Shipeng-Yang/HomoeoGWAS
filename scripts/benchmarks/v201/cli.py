def _validate_sealed_design(root: Path) -> None:
    lock = _strict_json(root / "design_lock.json")
    if lock.get("schema") != _LOCK_SCHEMA:
        raise CLIError("design lock schema mismatch")
    payload = {key: value for key, value in lock.items() if key != "design_hash"}
    if lock.get("design_hash") != sha256_payload(payload):
        raise CLIError("design lock hash mismatch")
    registry_path = root / "scenario_registry.tsv"
    registry = _read_registry(registry_path)
    _validate_locked_root(root, lock, registry, _sha256(registry_path))
    _validate_homoeogwas_configs(root, tuple(lock["config_hashes"]))


def command_init(args: argparse.Namespace) -> int:
    root = _canonical_root(args.root)
    if root.exists() and (not root.is_dir() or any(root.iterdir())):
        raise CLIError(f"init requires an absent or empty benchmark root: {root}")
    root.parent.mkdir(parents=True, exist_ok=True)
    existed = root.exists()
    if not existed:
        root.mkdir()
    try:
        prepared = _prepare_design(root, args.input_spec)
        _validate_presealed_design(root, prepared)
        _seal_design(root, prepared)
        if not (root / "design_lock.json").is_file():
            raise CLIError("design seal was not created")
    except Exception:
        shutil.rmtree(root, ignore_errors=True)
        if existed:
            root.mkdir()
        raise
    return 0


