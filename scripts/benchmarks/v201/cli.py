def _path_has_symlink(path: Path) -> bool:
    absolute = path.absolute()
    current = Path(absolute.anchor)
    for part in absolute.parts[1:]:
        current /= part
        if current.exists() and current.is_symlink():
            return True
    return False


def _canonical_root(path: Path) -> Path:
    if _path_has_symlink(path):
        raise CLIError("benchmark root and its parent path must not contain symlinks")
    return path.absolute()


def _sha256(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def _replicate_output_record(root: Path, output_root: Path) -> dict[str, Any]:
    """Hash every regular output below one benchmark-internal replicate root."""

    root = root.resolve()
    output_root.mkdir(parents=True, exist_ok=True)
    resolved = output_root.resolve()
    if resolved != root and root not in resolved.parents:
        raise CLIError("replicate output root escapes the benchmark root")
    if _path_has_symlink(output_root):
        raise CLIError("replicate output root must not contain symlinks")
    manifest = []
    total = 0
    for path in sorted(output_root.rglob("*")):
        if path.is_symlink():
            raise CLIError(f"replicate output must not be a symlink: {path}")
        if not path.is_file():
            continue
        relative = path.relative_to(root).as_posix()
        size = path.stat().st_size
        manifest.append({"path": relative, "size": size, "sha256": _sha256(path)})
        total += size
    return {
        "replicate_output_root": output_root.relative_to(root).as_posix(),
        "replicate_output_manifest": manifest,
        "replicate_output_bytes": total,
    }


def _attach_measurement(
    root: Path,
    output_root: Path,
    payload: Mapping[str, Any],
    measurement: Mapping[str, Any],
) -> dict[str, Any]:
    return {
        **dict(payload),
        **dict(measurement),
        **_replicate_output_record(root, output_root),
    }


def _git_commit() -> str:
    repository = Path(__file__).resolve().parents[3]
    completed = subprocess.run(
        ["git", "rev-parse", "HEAD"], cwd=repository, check=True,
        capture_output=True, text=True,
    )
    commit = completed.stdout.strip()
    if len(commit) != 40 or any(character not in _HEX for character in commit):
        raise CLIError("cannot resolve the benchmark harness Git commit")
    return commit


def _strict_input_spec(path: Path) -> dict[str, Any]:
    if not path.is_absolute():
        path = path.absolute()
    if path.is_symlink() or not path.is_file() or str(path) != str(path.resolve()):
        raise CLIError("input spec must be one canonical absolute regular JSON file")
    try:
        value = json.loads(
            path.read_text(encoding="utf-8"),
            object_pairs_hook=_reject_duplicate_pairs,
            parse_constant=lambda token: (_raise_nonfinite(token)),
        )
    except (OSError, UnicodeError, json.JSONDecodeError, ValueError) as error:
        raise CLIError(f"input spec is invalid JSON: {error}") from error
    if not isinstance(value, dict) or value.get("schema") != _INPUT_SPEC_SCHEMA:
        raise CLIError(f"input spec schema must be {_INPUT_SPEC_SCHEMA!r}")
    return value


def _reject_duplicate_pairs(pairs: list[tuple[str, Any]]) -> dict[str, Any]:
    result: dict[str, Any] = {}
    for key, value in pairs:
        if key in result:
            raise ValueError(f"duplicate JSON key: {key}")
        result[key] = value
    return result


def _raise_nonfinite(token: str) -> Any:
    raise ValueError(f"non-finite JSON value: {token}")


def _external_file(value: Any, label: str) -> Path:
    if not isinstance(value, str) or not value:
        raise CLIError(f"missing input path: {label}")
    candidate = Path(value)
    if (
        not candidate.is_absolute()
        or str(candidate) != str(candidate.resolve())
        or candidate.is_symlink()
        or not candidate.is_file()
    ):
        raise CLIError(f"{label} must be a canonical absolute regular file: {value}")
    return candidate


def _write_yaml(path: Path, value: Mapping[str, Any]) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(
        yaml.safe_dump(dict(value), sort_keys=False, allow_unicode=True),
        encoding="utf-8",
    )


